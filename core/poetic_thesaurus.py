def lookup_poetic_words(word: str) -> Optional[Dict[str, Any]]:
    """
    단어에 매칭되는 시어 감각 사전 항목을 검색합니다.
    1) 완전 일치
    2) 키워드 리스트 일치
    3) 부분 일치 (단어가 키를 포함하거나, 키가 단어를 포함)
    """
    clean_word = (word or "").strip()
    if not clean_word:
        return None

    # 1. 키값 직접 일치
    if clean_word in POETIC_THESAURUS_DB:
        return {
            "matched_key": clean_word,
            "data": POETIC_THESAURUS_DB[clean_word]
        }

    # 2. 키워드 리스트 일치 검사
    for key, item in POETIC_THESAURUS_DB.items():
        if clean_word in item.get("keywords", []):
            return {
                "matched_key": key,
                "data": item
            }

    # 3. 부분 포함 검사
    for key, item in POETIC_THESAURUS_DB.items():
        if key in clean_word or any(kw in clean_word for kw in item.get("keywords", [])):
            return {
                "matched_key": key,
                "data": item
            }

    # 4. 역방향: clean_word가 key의 부분문자열인 경우 (2글자 이상)
    if len(clean_word) >= 2:
        for key, item in POETIC_THESAURUS_DB.items():
            if clean_word in key:
                return {
                    "matched_key": key,
                    "data": item
                }

    return None


def get_all_categories_summary() -> List[Dict[str, Any]]:
    """전체 시어 사전의 대표 주제 목록과 미리보기를 반환합니다."""
    res = []
    for key, item in POETIC_THESAURUS_DB.items():
        categories_dict = item.get("categories", {})
        first_cat = list(categories_dict.keys())[0] if categories_dict else ""
        first_examples = categories_dict.get(first_cat, [])[:4]
        res.append({
            "key": key,
            "category_preview": first_cat,
            "examples": first_examples,
            "all_categories": list(categories_dict.keys())
        })
    return res


def suggest_poetic_synonyms_ai(word: str, poem_context: str = "") -> Dict[str, Any]:
    """
    Gemini AI를 활용하여 시적 문맥에 최적화된 시어, 방언, 은유적 유의어를 실시간 생성합니다.
    API 키가 없거나 호출 실패 시 내부 사전에서 스마트하게 추출하여 100% 무과금 fallback을 보장합니다.
    """
    clean_word = (word or "").strip()
    if not clean_word:
        return {"word": "", "suggestions": [], "source": "none"}

    # 1. 내부 정적 사전 우선 조회 (가장 정확한 서정 데이터)
    db_match = lookup_poetic_words(clean_word)
    fallback_words: List[Dict[str, str]] = []
    if db_match:
        for cat_name, words in db_match["data"].get("categories", {}).items():
            for w in words[:3]:
                pure = w.split("(")[0].strip()
                meta = f"({w.split('(')[1]}" if "(" in w else f"[{cat_name}]"
                fallback_words.append({"word": pure, "desc": meta, "category": cat_name})

    # 2. Gemini API 호출 시도 (키가 있을 경우 실시간 문맥 추천)
    _api_key = get_gemini_api_key()
    if _api_key:
        try:
            from google import genai
            client = genai.Client(api_key=_api_key)
            
            system_instruction = (
                "당신은 백석, 박목월, 김소월의 정서를 계승한 한국 정통 서정시 어휘 전문 시인입니다. "
                "사용자가 시를 퇴고하며 선택한 특정 단어에 대해, 시적 호흡과 정서적 울림을 깊게 만들어줄 "
                "서정적 시어, 토속어/방언, 은유적 대체어를 추천해야 합니다.\n"
                "반드시 아래의 정밀한 JSON 포맷으로만 응답하세요. 다른 설명 문장은 일절 배제하세요:\n"
                "[\n"
                '  {"word": "대체단어", "desc": "정서적 느낌 또는 방언지역", "category": "먹먹함/토속/은유/소리 중 택1"},\n'
                "  ...\n"
                "]"
            )

            prompt = (
                f"선택한 단어: 『{clean_word}』\n"
            )
            if poem_context:
                prompt += f"시 본문 문맥(주변 시행):\n{poem_context[:300]}\n"
            prompt += (
                f"\n단어 『{clean_word}』를 시 본문에서 교체했을 때 문학적 감각과 여운을 더해줄 "
                f"고품격 서정 시어 및 향토 방언 4~6개를 추천해 주세요."
            )

            active_model = os.getenv("GEMINI_MODEL", "gemini-3.8-flash")
            response = client.models.generate_content(
                model=active_model,
                contents=prompt,
                config={
                    "system_instruction": system_instruction,
                    "temperature": 0.75,
                }
            )

            text = response.text or ""
            # JSON 파싱 시도
            import json
            match = re.search(r'\[.*\]', text, re.DOTALL)
            if match:
                ai_list = json.loads(match.group(0))
                if isinstance(ai_list, list) and len(ai_list) > 0:
                    clean_results = []
                    for item in ai_list:
                        if isinstance(item, dict) and "word" in item:
                            clean_results.append({
                                "word": str(item.get("word", "")).strip(),
                                "desc": str(item.get("desc", "")).strip(),
                                "category": str(item.get("category", "시적 은유")).strip()
                            })
                    if clean_results:
                        return {
                            "word": clean_word,
                            "matched_key": db_match["matched_key"] if db_match else clean_word,
                            "suggestions": clean_results[:6],
                            "source": "gemini_ai"
                        }
        except Exception as e:
            print(f"[Poetic Thesaurus AI Fallback] Gemini API warning: {e}")

    # 3. Fallback: 오프라인 사전 기반 결과 반환
    if fallback_words:
        return {
            "word": clean_word,
            "matched_key": db_match["matched_key"] if db_match else clean_word,
            "suggestions": fallback_words[:6],
            "source": "thesaurus_db"
        }

    # 4. 아무것도 매칭되지 않았을 때의 서정 시적 기본 제안
    default_poetic = [
        {"word": f"{clean_word}결", "desc": "부드러운 숨결", "category": "서정 결"},
        {"word": f"아련한 {clean_word}", "desc": "아스라한 기억", "category": "정서"},
        {"word": f"소복한 {clean_word}", "desc": "풍성한 침묵", "category": "시적 묘사"},
        {"word": "그리움", "desc": "마음 깊은 울림", "category": "서정 테마"}
    ]
    return {
        "word": clean_word,
        "matched_key": clean_word,
        "suggestions": default_poetic,
        "source": "heuristic"
    }
